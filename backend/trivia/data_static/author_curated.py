def A(mvp=(), fmvp=(), dpoy=(), roty=None, smoy=(), allstar=0, allnba=0, rings=()):
    return {
        "mvp": list(mvp), "fmvp": list(fmvp), "dpoy": list(dpoy), "roty": roty,
        "smoy": list(smoy), "allstar_count": allstar, "allnba_count": allnba,
        "rings": list(rings),
    }


def T(*stints):
    """Each stint: (abbr, start, end, gp, ppg[, name_override])."""
    out = []
    for s in stints:
        abbr, start, end, gp, ppg = s[0], s[1], s[2], s[3], s[4]
        name = s[5] if len(s) > 5 else NAME[abbr]
        out.append({"abbr": abbr, "name": name, "start_year": start,
                    "end_year": end, "gp": gp, "ppg": ppg})
    return out


