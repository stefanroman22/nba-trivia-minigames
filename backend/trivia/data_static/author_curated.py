def _norm(s):
    s = unicodedata.normalize("NFKD", s)
    s = "".join(c for c in s if not unicodedata.combining(c))
    return "".join(c for c in s.lower() if c.isalnum())


# Explicit id overrides for collision-prone names (verified from the static list).
OVERRIDE = {
    "Gary Payton": 56,       # The Glove (not Gary Payton II, 1627780)
    "Josh Smith": 2746,      # J-Smoove (ATL)
    "Gerald Green": 101123,
    "Corey Brewer": 201147,
}


def resolve(row):
    name = row["full_name"]
    if name in OVERRIDE and OVERRIDE[name]:
        pid = OVERRIDE[name]
        rec = static_players.find_player_by_id(pid)
        return pid, (rec["full_name"] if rec else name)
    res = static_players.find_players_by_full_name(name)
    if not res:
        return None, None
    nq = _norm(name)
    exact = [r for r in res if _norm(r["full_name"]) == nq]
    pool = exact or res
    want = row["is_active"]
    active_pool = [r for r in pool if r["is_active"] == want]
    pool = active_pool or pool
    chosen = pool[0]
    return chosen["id"], chosen["full_name"]


def main():
    with open(CAREER_PATH_SEED, "r", encoding="utf-8") as f:
        base = json.load(f)

    resolved = []
    dropped = []
    seen_ids = set()

    # Base 24 rows already carry valid ids — keep verbatim.
    for row in base:
        resolved.append(row)
        seen_ids.add(row["person_id"])

    ambiguous = []
    for row in ROSTER:
        pid, canonical = resolve(row)
        if pid is None:
            dropped.append(row["full_name"])
            continue
        if pid in seen_ids:
            # Duplicate of a base row (or another authored row) — skip.
            dropped.append(f"{row['full_name']} (dup id {pid})")
            continue
        # Use nba_api's canonical (accented) full_name; keep authored ASCII as alias.
        aliases = list(row["aliases"])
        if canonical != row["full_name"] and row["full_name"] not in aliases:
            aliases.append(row["full_name"])
        row = dict(row)
        row["person_id"] = pid
        row["full_name"] = canonical
        row["aliases"] = aliases
        # Order keys: person_id first for readability.
        ordered = {"person_id": pid}
        ordered.update({k: v for k, v in row.items() if k != "person_id"})
        resolved.append(ordered)
        seen_ids.add(pid)

    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(resolved, f, ensure_ascii=False, indent=1)

    tiers = {1: 0, 2: 0, 3: 0, 4: 0}
    four_plus = 0
    for r in resolved:
        tiers[r["fame_tier"]] = tiers.get(r["fame_tier"], 0) + 1
        if len(r["teams"]) >= 4:
            four_plus += 1

    print(f"WROTE {OUT}")
    print(f"total={len(resolved)}  tier1={tiers[1]} tier2={tiers[2]} tier3={tiers[3]} tier4={tiers[4]}")
    print(f"players with 4+ stints: {four_plus}")
    if dropped:
        print(f"DROPPED ({len(dropped)}): {dropped}")
    if ambiguous:
        print(f"AMBIGUOUS: {ambiguous}")


if __name__ == "__main__":
    main()
